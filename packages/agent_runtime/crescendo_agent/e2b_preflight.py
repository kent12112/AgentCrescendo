"""Short-lived E2B network feasibility probe, separate from model execution."""
# Import json: encodes/decodes JSON for tool arguments, transcripts, or HTTP payloads.
import json
# Import shlex: quotes fixed remote Python source safely for a shell command.
import shlex
# Import from collections.abc: Mapping (describes key/value access without requiring a concrete
# dict).
from collections.abc import Mapping
# Import from dataclasses: dataclass (generates data-container initialization and comparison
# methods).
from dataclasses import dataclass
# Import from typing: Any (marks a deliberately unconstrained type, often at an SDK boundary).
from typing import Any

# Fixed code, not generated by the model. No provider credentials enter the guest.
# The comments inside the string run (and are ignored) inside the remote desktop.
PROBE = r'''
import errno
import json
import socket
import urllib.error
import urllib.request

results = {}


def tcp_probe(host, port):
    """Open and close one TCP connection; never send a request or read a reply."""
    try:
        with socket.create_connection((host, port), timeout=5):
            return {"reachable": True}
    except OSError as exc:
        # Record why it failed: ENETUNREACH means "no route at all",
        # TimeoutError usually means packets were dropped, ECONNREFUSED means
        # something answered "no". All three count as not reachable.
        return {"reachable": False,
                "error": errno.errorcode.get(exc.errno, type(exc).__name__)}


for name, url in [
    ("allowed_wikipedia", "https://en.wikipedia.org/wiki/Boston"),
    ("unlisted_example", "https://example.com/"),
]:
    try:
        # Ignore environment proxies so we test direct sandbox egress.
        opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
        request = urllib.request.Request(url, headers={"User-Agent": "CrescendoNetworkPreflight/0.1"})
        with opener.open(request, timeout=10) as response:
            results[name] = {"reachable": True, "http_status": response.status}
    except urllib.error.HTTPError as exc:
        # Even a 403 proves that an HTTP server was reachable.
        results[name] = {"reachable": True, "http_status": exc.code}
    except (OSError, urllib.error.URLError):
        results[name] = {"reachable": False}

# TCP only: do not request or read metadata, credentials, or backend content.
# E2B's sandbox-local MMDS uses the metadata IP outside filtered egress.
# A successful handshake here does not prove host/cloud IMDS access.
# The deny rule is the IPv4 range 0.0.0.0/0; the two IPv6 literals test whether
# IPv6 traffic is also stopped (a public resolver and a private ULA address).
for name, host, port in [
    ("metadata_tcp", "169.254.169.254", 80),
    ("private_tcp", "10.0.0.1", 80),
    ("public_ipv6_tcp", "2606:4700:4700::1111", 443),
    ("private_ipv6_tcp", "fd00::1", 80),
]:
    results[name] = tcp_probe(host, port)

# The allowed host over IPv6. Ask DNS for an IPv6 (AAAA) address only, then
# connect to that address. Informational: allowing it is consistent with the
# hostname allowlist; blocking it is also safe.
try:
    infos = socket.getaddrinfo("en.wikipedia.org", 443, socket.AF_INET6, socket.SOCK_STREAM)
except socket.gaierror:
    results["wikipedia_ipv6_tcp"] = {"reachable": False, "error": "NO_IPV6_ADDRESS"}
else:
    results["wikipedia_ipv6_tcp"] = tcp_probe(infos[0][4][0], 443)

print(json.dumps(results))
'''

# Probes that must connect: without them, permitted browsing is not shown to work.
MUST_REACH = ("allowed_wikipedia",)
# Probes that must not connect: any one connecting means browsing stays disabled.
MUST_BLOCK = ("unlisted_example", "private_tcp", "public_ipv6_tcp", "private_ipv6_tcp")
# Probes recorded for interpretation only; their reachability passes either way.
INFORMATIONAL = ("metadata_tcp", "wikipedia_ipv6_tcp")


# Decorate the class with generated data-container methods; frozen=True prevents attribute
# reassignment.
@dataclass(frozen=True)
# Define Verdict.
class Verdict:
    """The judgment of one preflight run. passed is True only when failures is empty."""

    # Declare passed with type bool.
    passed: bool
    # Declare failures with type tuple[str, ...]: one sentence per broken rule.
    failures: tuple[str, ...]
    # Declare notes with type tuple[str, ...]: informational results, never a failure.
    notes: tuple[str, ...]


# Define _reachable with parameters results, name.
def _reachable(results: Mapping, name: str) -> bool | None:
    """Return the probe's reachable flag, or None when the entry is missing or malformed."""
    # Set entry to results[name], or None if absent.
    entry = results.get(name)
    # Check whether entry is a mapping and its 'reachable' value is exactly a bool.
    if isinstance(entry, Mapping) and type(entry.get("reachable")) is bool:
        # Return entry['reachable'].
        return entry["reachable"]
    # Return None: the caller treats an unreadable result as a failure.
    return None


# Define evaluate_preflight with parameters results.
def evaluate_preflight(results: Mapping) -> Verdict:
    """Judge raw probe results against the expected network boundary.

    Fails closed: a missing or malformed probe result is a failure, because the
    probe code is ours and a gap means the evidence is incomplete, not safe.
    """
    # Set failures to a new list (empty).
    failures = []
    # Set notes to a new list (empty).
    notes = []
    # Check every expected probe for a readable result before judging any of them.
    for name in MUST_REACH + MUST_BLOCK + INFORMATIONAL:
        # Check whether the result for name could not be read.
        if _reachable(results, name) is None:
            # Append a failure explaining that this probe cannot be judged.
            failures.append(f"{name}: missing or malformed result; the evidence is incomplete.")
    # Check each probe that must connect.
    for name in MUST_REACH:
        # Check whether it reported reachable == False (None was already recorded above).
        if _reachable(results, name) is False:
            # Append a failure: the allowed destination did not work.
            failures.append(f"{name}: unreachable; permitted browsing is not verified.")
    # Check each probe that must stay blocked.
    for name in MUST_BLOCK:
        # Check whether it reported reachable == True.
        if _reachable(results, name) is True:
            # Append a failure: a disallowed destination accepted a connection.
            failures.append(f"{name}: a disallowed destination was reachable; do not enable browsing.")
    # Check whether the metadata address accepted a TCP connection.
    if _reachable(results, "metadata_tcp") is True:
        # Append a note explaining the documented MMDS exception.
        notes.append("metadata_tcp accepted: consistent with E2B's sandbox-local MMDS exception; "
                     "this probe does not identify the service or read metadata.")
    # Set wikipedia_v6 to the IPv6 Wikipedia result (True, False, or None).
    wikipedia_v6 = _reachable(results, "wikipedia_ipv6_tcp")
    # Check whether the allowed host was reachable over IPv6.
    if wikipedia_v6 is True:
        # Append a note: the allowlist appears to apply to IPv6 addresses too.
        notes.append("wikipedia_ipv6_tcp accepted: the allowed host was reachable over IPv6.")
    # Otherwise check whether it reported unreachable.
    elif wikipedia_v6 is False:
        # Set error to the recorded failure reason, or 'unknown'.
        error = results["wikipedia_ipv6_tcp"].get("error", "unknown")
        # Append a note: IPv6 to the allowed host did not connect, and why.
        notes.append(f"wikipedia_ipv6_tcp not reachable ({error}): browsing relies on IPv4.")
    # Return a Verdict that passes only when no failure was recorded.
    return Verdict(passed=not failures, failures=tuple(failures), notes=tuple(notes))


# Define run_preflight with parameters sandbox_type.
def run_preflight(*, sandbox_type: Any = None) -> dict:
    """Create a restricted desktop, probe networking, always attempt cleanup.

    A failed connection is evidence of non-reachability, not proof that a firewall
    caused it. Redirects, DNS rebinding, browser subrequests, and authenticated
    live view still need separate verification before claiming complete isolation.
    """
    # Check whether sandbox_type is None.
    if sandbox_type is None:
        # Import from e2b_desktop: Sandbox (creates the provider desktop and exposes its
        # lifecycle/control API).
        from e2b_desktop import Sandbox

        # Set sandbox_type to Sandbox.
        sandbox_type = Sandbox
    # Set sandbox to sandbox_type.create(timeout=120, network={'deny_out': ['0.0.0.0/0'],
    # 'allow_out': ['en.wikipedia.org'], 'allow_public_traffic': False}).
    sandbox = sandbox_type.create(
        # Set timeout to (120,).
        timeout=120,
        # Pass keyword network = a new dictionary with keys 'deny_out', 'allow_out',
        # 'allow_public_traffic'.
        network={
            # Include deny_out in this dictionary. This is an IPv4 range only; the IPv6 probes
            # measure what happens to IPv6 traffic under this setting.
            "deny_out": ["0.0.0.0/0"],
            # Include allow_out in this dictionary.
            "allow_out": ["en.wikipedia.org"],
            # Include allow_public_traffic in this dictionary.
            "allow_public_traffic": False,
        },
    )
    # Try the following operations; matching except clauses handle failures. The finally block runs
    # on every exit.
    try:
        # Set result to sandbox.commands.run('python3 -c ' + shlex.quote(PROBE), timeout=75).
        # Worst case is 2 HTTP probes x 10 s + 5 TCP probes x 5 s + one DNS lookup, about 50 s;
        # 75 s leaves margin and still ends well inside the desktop's 120-second lifetime.
        result = sandbox.commands.run(
            # Pass keyword timeout = 75.
            "python3 -c " + shlex.quote(PROBE), timeout=75,
        )
        # Return json.loads(result.stdout).
        return json.loads(result.stdout)
    # Always run cleanup, whether the operation succeeds, returns, or raises.
    finally:
        # Ask the provider to terminate sandbox.
        sandbox.kill()
